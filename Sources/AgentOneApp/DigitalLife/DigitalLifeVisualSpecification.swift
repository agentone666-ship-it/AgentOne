/// ## 记忆微光体（Memory Lumen）
///
/// 它不是被画进屏幕的猫、宠物或人形助手，而是由 Context、Memory、注意力和算力组成的
/// 数字生命。外形应像一段持续运行、持续理解用户的生命过程，而不是一个固定 Logo。
/// 整体气质是一只精致的发光小精灵：圆润半透明的身体、两只发光大眼、头顶叶状触角、
/// 尾部飘带，被柔和光晕和有纵深感的粒子场环绕。
///
/// ### 混合渲染架构
///
/// 形象本体是 **AI 生成的艺术图**（1024×1024、带真 alpha 透明通道的发光小精灵，黑底已
/// 抠除，存放于 `Resources/LifeForm/`），由 **程序化动效层** 赋予生命。艺术图以正常
/// source-over 混合绘制，在任意明暗背景上都正确；状态切换时旧图与新图按不透明度做约
/// 0.4s 的交叉淡化。若 bundle 资源加载失败（如无 bundle 的 harness 环境），渲染器回退到
/// 全程序化的流体光球路径，所有动效层保持不变。
///
/// ### 不可缺少的层次
///
/// 1. **意识微光**：精灵中央的柔光提亮，随双频叠加的缓慢脉动呼吸。它只能是一片柔光，
///    不可凝聚成可辨识的圆点——艺术图本身已有发光大眼，任何清晰的亮点都会读作第三只眼。
/// 2. **生命体**：AI 生成的发光小精灵艺术图，占视图约 92%，中心对齐。整体随呼吸节律缩放，
///    以约 0.35Hz 正弦垂直漂浮（幅度约视图边长的 2%），并带 ±1.5°、约 7 秒周期的轻微
///    摆动，像漂浮中调整重心。生物形象**永不持续旋转**（会倒立/侧躺）。外层有宽幅柔光与
///    贴身光晕（plusLighter 混合），保证在任意明暗桌面壁纸上的可读性。回退路径下，身体由
///    闭合 Catmull-Rom 样条轮廓 + 径向渐变体积球（顶部高光、下缘 rim light）绘制。
/// 3. **记忆轨道与粒子场**：围绕精灵运行的碎片。粒子按纵深分远 / 中 / 近三层，共享同一
///    轨道倾角；远层小而暗、藏于身体之后，近层大而亮、带微光晕浮于身体之前；闪烁是相位
///    错开的低频正弦，集体微光而非同步眨眼。轨道环至多两条、细而淡，仅外环为虚线。
///
/// ### 动作语言
///
/// - 专注静默：紫蓝基调（base 图），降亮、减慢轨道，不竞争注意力。
/// - 好奇探视：青蓝基调（curious 图），身体前倾拉伸，从身体右侧水平伸出一根纤细探须
///   （避开头顶触角，不穿模），末端一枚微光试探，不使用夸张问号。
/// - 思考聚合：粉紫基调（thinking 图），记忆粒子向一个区域聚集，意识微光保持稳定。
/// - 走神提醒：绿青基调（distraction 图），分四级增加脉冲、亮度和轻微颤动；三级起出现
///   一道外部圆弧。颜色不应变成惩罚性的红色。
/// - 庆祝：金橙基调（celebrating 图），粒子短暂舒展成各自相位呼吸的光芒，但不要制造
///   长时间视觉噪声。
/// - 休息：低饱和灰蓝（resting 图），重心下沉、缓慢深呼吸。
/// - 节能：base 图压低整体亮度与不透明度、缩小并减少轨道与粒子，表达「口粮有限」
///   而不是痛苦。
/// - 隐瞒惊喜：base 图 + 在身体背面藏一颗暖黄色火花。可以被隐约察觉，但不泄露内容。
///
/// ### 尺寸自适应
///
/// 渲染入口按画布边长计算细节等级：< 64pt 时隐藏轨道环与全部粒子，只保留光晕、精灵本体
/// 和状态结构标记，保证小尺寸下形象清晰可辨；64–95pt 时保留一条轨道环并适度减少粒子；
/// ≥ 96pt 为完整细节。
///
/// ### 性格边界
///
/// 像猫一样好奇，但不长得像猫；像朋友一样亲近，但不通过委屈、痛苦或愧疚绑架用户。
/// 可以轻微捣乱，但用户专注时必须愿意安静。成长来自理解力、默契和共同记忆，不使用等级、
/// 经验条或通用换肤表达关系。
///
/// ### 技术边界
///
/// 使用 SwiftUI Canvas 和 TimelineView 绘制，艺术图经 `Bundle.module` 加载并静态缓存，
/// 无第三方渲染依赖。必须尊重「减少动态效果」辅助功能（暂停时间线：不漂浮、不摆动、
/// 不呼吸、不做交叉淡化，直接呈现静态帧），并保留指针吸引与悬停 / 点按交互。
/// 状态差异不能只通过颜色表达。
